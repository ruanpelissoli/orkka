namespace Orkka.Modules.Execution.Agents;

using Microsoft.Extensions.Logging;

/// <summary>
/// Writes the controlled <c>.env</c> "guard" files that defang the gemini CLI's dotenv
/// discovery. The CLI walks UP from its working directory and dotenv-loads the FIRST
/// <c>.gemini/.env</c> or <c>.env</c> it finds — exclusively, continuing past $HOME to
/// the filesystem root, with <c>~/.gemini/.env</c> only as a last-resort fallback. Left
/// alone, an agent in a cache worktree (<c>~/.orkka/repos/…</c>) loads whatever
/// <c>.env</c> sits on that ancestor path into its own process — which bypasses the
/// Layer-2 env sanitizer entirely (the sanitizer can only blank variables the RUNNER
/// holds, not files a child CLI reads by itself). Verified live 2026-07-12:
/// <c>~/.orkka/.env</c> handed a gemini agent the runner token and Postgres password.
///
/// A guard at every Orkka-owned workspace root stops the walk at a file we control.
/// The guard mirrors <c>~/.gemini/.env</c> (the CLI's documented API-key home) so
/// API-key auth behaves identically in cloud-cloned and local-source worktrees, and
/// falls back to a key the runner supplies (ORKKA_GEMINI_API_KEY from the stack env)
/// so a key configured once for image generation also powers gemini agents. Only the
/// gemini CLI needs this: current codex reads solely <c>~/.codex/.env</c> and the
/// copilot CLI loads no dotenv files at all.
/// </summary>
public static class GeminiDotenvGuard
{
    /// <summary>First line of every guard file — cleanup code only ever deletes a lone
    /// <c>.env</c> that carries this marker, never a user's own file.</summary>
    public const string Marker = "# Generated by Orkka - gemini CLI dotenv guard.";

    private const string Header =
        Marker + "\n" +
        "# The gemini CLI loads the first .env found walking up from its working directory.\n" +
        "# This file stops that walk inside Orkka-managed workspaces so agent processes\n" +
        "# never dotenv-load unrelated secrets, and mirrors ~/.gemini/.env so gemini\n" +
        "# API-key auth works in every task worktree. Regenerated on every run - do not edit.\n";

    /// <summary>Optional key the runner resolved from its own configuration
    /// (ORKKA_GEMINI_API_KEY in the stack env file). Used only when the mirrored
    /// <c>~/.gemini/.env</c> does not itself carry a usable key. Set once at startup.</summary>
    public static string? FallbackApiKey { get; set; }

    /// <summary>Test seam: overrides where the user's gemini dotenv file is read from.</summary>
    internal static string? UserGeminiEnvPathOverride { get; set; }

    /// <summary>Writes (or refreshes) the guard file <c>{directory}/.env</c>. Never
    /// throws — a failed guard write must not block a task run; the stack-env rename
    /// keeps real secrets out of the walk path even without the guard.</summary>
    public static void Refresh(string directory, ILogger? logger = null)
    {
        try
        {
            Directory.CreateDirectory(directory);
            var guardPath = Path.Combine(directory, ".env");

            // Never overwrite a file that isn't ours — an unmarked .env here was put
            // there by the user (or is a repo's own file) and wins over the guard.
            if (File.Exists(guardPath))
            {
                using var reader = new StreamReader(guardPath);
                if (reader.ReadLine() is { } firstLine && !firstLine.StartsWith(Marker, StringComparison.Ordinal))
                    return;
            }

            var content = BuildContent(ReadUserGeminiEnv(), FallbackApiKey);
            if (!File.Exists(guardPath) || File.ReadAllText(guardPath) != content)
                File.WriteAllText(guardPath, content);
        }
        catch (Exception ex)
        {
            logger?.LogWarning("Could not write gemini dotenv guard in {Directory}: {Message}",
                directory, ex.Message);
        }
    }

    /// <summary>Deletes a guard file (marker-checked) so an otherwise-empty Orkka
    /// worktree root can be removed. Returns true when no guard remains.</summary>
    public static bool TryDeleteGuard(string directory)
    {
        try
        {
            var guardPath = Path.Combine(directory, ".env");
            if (!File.Exists(guardPath))
                return true;

            using (var reader = new StreamReader(guardPath))
            {
                if (reader.ReadLine() is not { } firstLine
                    || !firstLine.StartsWith(Marker, StringComparison.Ordinal))
                    return false;
            }

            File.Delete(guardPath);
            return true;
        }
        catch
        {
            return false;
        }
    }

    internal static string BuildContent(string? userGeminiEnv, string? fallbackApiKey)
    {
        var content = Header;

        if (!string.IsNullOrWhiteSpace(userGeminiEnv))
            content += "\n" + userGeminiEnv.Trim() + "\n";

        if (!string.IsNullOrWhiteSpace(fallbackApiKey)
            && !HasApiKey(userGeminiEnv))
            content += $"\nGEMINI_API_KEY={fallbackApiKey.Trim()}\n";

        return content;
    }

    /// <summary>Minimal dotenv scan for a non-blank GEMINI_API_KEY / GOOGLE_API_KEY
    /// (`#` comments, optional `export ` prefix, optional quotes) — mirrors the rules
    /// ProviderDetection applies to the same file.</summary>
    internal static bool HasApiKey(string? envText)
    {
        if (string.IsNullOrWhiteSpace(envText))
            return false;

        foreach (var rawLine in envText.Split('\n'))
        {
            var line = rawLine.Trim();
            if (line.Length == 0 || line.StartsWith('#'))
                continue;
            if (line.StartsWith("export ", StringComparison.Ordinal))
                line = line["export ".Length..].TrimStart();

            var eq = line.IndexOf('=');
            if (eq <= 0)
                continue;
            if (line[..eq].Trim() is not ("GEMINI_API_KEY" or "GOOGLE_API_KEY"))
                continue;

            if (!string.IsNullOrWhiteSpace(line[(eq + 1)..].Trim().Trim('"', '\'')))
                return true;
        }

        return false;
    }

    private static string? ReadUserGeminiEnv()
    {
        try
        {
            var path = UserGeminiEnvPathOverride ?? Path.Combine(
                Environment.GetFolderPath(Environment.SpecialFolder.UserProfile), ".gemini", ".env");
            return File.Exists(path) ? File.ReadAllText(path) : null;
        }
        catch
        {
            return null;
        }
    }
}
