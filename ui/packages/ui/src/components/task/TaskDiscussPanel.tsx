import { useCallback, useEffect, useMemo, useRef, useState } from "react";
import { useTranslations } from "use-intl";
import { cn } from "@/lib/utils";
import { Avatar, Button, Markdown, Select, useToast } from "@/components/ui";
import { RequirePermission } from "@/components/permissions/RequirePermission";
import { usePermissions } from "@/hooks/use-permissions";
import { useClientApi } from "@/hooks/use-client-api";
import {
  QuestionAnswers,
  QuestionsCard,
  QuestionsGroup,
  QuestionsInProgress,
  parseQuestionAnswers,
  splitQuestionSegments,
} from "@/components/chat/QuestionBlocks";
import { api, extractErrorMessage } from "@/lib/api";
import { streamTaskChatMessage } from "@/lib/sse";
import { laneLabel as laneLabelFor } from "../board/lane-label";
import { formatMessageTime } from "@/lib/utils";
import type { ApplyTaskChatRequest, ApplyTaskChatResult, TaskChat, TaskChatMessage } from "@/lib/types";
import {
  TASK_DISCUSS_APPLIED_KEYS,
  TASK_DISCUSS_APPLY_KEYS,
  taskDiscussApplyMode,
} from "./task-discuss-labels";

interface TaskDiscussPanelProps {
  taskId: string;
  projectId: string;
  /** The task's live lane — decides what "apply" does and how its buttons read. */
  lane: string;
  /** Fires after an apply landed, with the lane the task moved to. The host refreshes. */
  onApplied?: (result: ApplyTaskChatResult) => void;
}

/** The loaded conversation plus the messages added to it since (optimistic + streamed). */
interface LoadedChat {
  /** The agent the request asked for ("" = the task's default agent). */
  key: string;
  chat: TaskChat;
  messages: TaskChatMessage[];
}

const REMOTE_RUN_POLL_MS = 3000;

/**
 * The task's "Discuss" tab: an immediate back-and-forth with an agent about this task. The
 * agent reads the ticket and the repository, asks questions and proposes a plan; nothing
 * reaches the task until the user applies a reply (or a summary of the discussion) — as an
 * answer, a plan-change request or a plain post, depending on the lane. Each task + agent
 * pair has its own conversation; the picker switches between them.
 */
function TaskDiscussPanel({ taskId, projectId, lane, onApplied }: TaskDiscussPanelProps) {
  const t = useTranslations("dashboard.taskDiscuss");
  const tCommon = useTranslations("common");
  const tDash = useTranslations("dashboard");
  const { toast } = useToast();
  const { has } = usePermissions();
  const canExecute = has("TasksExecute");
  const withToken = useClientApi();

  // "" = the task's own agent; the server answers with which one that is.
  const [requestedAgentId, setRequestedAgentId] = useState("");
  const [loaded, setLoaded] = useState<LoadedChat | null>(null);
  const [loadError, setLoadError] = useState<{ key: string; message: string } | null>(null);
  const [reloadTick, setReloadTick] = useState(0);

  const [isStreaming, setIsStreaming] = useState(false);
  const [streamingText, setStreamingText] = useState("");
  const [thinkingText, setThinkingText] = useState("");
  const [toolLabel, setToolLabel] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);
  const [inputValue, setInputValue] = useState("");
  const [applying, setApplying] = useState<string | null>(null);
  const streamingTextRef = useRef("");
  const scrollRef = useRef<HTMLDivElement>(null);

  const current = loaded && loaded.key === requestedAgentId ? loaded : null;
  const chat = current?.chat ?? null;
  const messages = useMemo(() => current?.messages ?? [], [current]);
  const currentLoadError = loadError && loadError.key === requestedAgentId ? loadError.message : null;
  const isLoading = !current && !currentLoadError;
  // A reply generated by an earlier visit (or another tab) is still running server-side.
  const remoteRunActive = !isStreaming && !!chat?.hasActiveRun;
  const busy = isStreaming || remoteRunActive;

  // Load (and, while a detached reply runs, poll) the conversation of the picked agent.
  useEffect(() => {
    let cancelled = false;
    const key = requestedAgentId;
    withToken((token) => api.tasks.getChat(taskId, key || null, token))
      .then((next) => {
        if (cancelled) return;
        setLoaded({ key, chat: next, messages: next.messages });
      })
      .catch((err: unknown) => {
        if (cancelled) return;
        setLoadError({ key, message: extractErrorMessage(err, t("loadFailed")) });
      });
    return () => {
      cancelled = true;
    };
  }, [taskId, requestedAgentId, reloadTick, withToken, t]);

  useEffect(() => {
    if (!remoteRunActive) return;
    const timer = setTimeout(() => setReloadTick((n) => n + 1), REMOTE_RUN_POLL_MS);
    return () => clearTimeout(timer);
  }, [remoteRunActive, loaded]);

  // Keep the newest message in view as the conversation grows.
  useEffect(() => {
    const el = scrollRef.current;
    if (el) el.scrollTop = el.scrollHeight;
  }, [messages.length, streamingText, thinkingText, isStreaming]);

  const resetStream = useCallback(() => {
    setIsStreaming(false);
    setStreamingText("");
    setThinkingText("");
    setToolLabel(null);
    streamingTextRef.current = "";
  }, []);

  const sendMessage = useCallback(
    async (raw: string) => {
      const content = raw.trim();
      if (!content || !current || busy) return;
      const key = current.key;
      const agentId = current.chat.agentId;
      setError(null);
      setLoaded((prev) =>
        prev && prev.key === key
          ? {
              ...prev,
              messages: [
                ...prev.messages,
                {
                  id: `temp-user-${Date.now()}`,
                  role: "user",
                  content,
                  createdAt: new Date().toISOString(),
                },
              ],
            }
          : prev
      );
      setIsStreaming(true);
      setStreamingText("");
      setThinkingText("");
      setToolLabel(null);
      streamingTextRef.current = "";

      await withToken((token) =>
        streamTaskChatMessage(taskId, content, agentId, token, {
          onChunk: (text) => {
            streamingTextRef.current += text;
            setStreamingText(streamingTextRef.current);
            setToolLabel(null);
          },
          onThinking: (text) => setThinkingText((prev) => prev + text),
          onToolUse: (label) => setToolLabel(label),
          onDone: () => {
            const finalText = streamingTextRef.current;
            // Show the reply at once; the reload swaps in the persisted ids "apply" needs.
            if (finalText) {
              setLoaded((prev) =>
                prev && prev.key === key
                  ? {
                      ...prev,
                      messages: [
                        ...prev.messages,
                        {
                          id: `temp-assistant-${Date.now()}`,
                          role: "assistant",
                          content: finalText,
                          createdAt: new Date().toISOString(),
                        },
                      ],
                    }
                  : prev
              );
            }
            resetStream();
            setReloadTick((n) => n + 1);
          },
          onError: (err) => {
            // Includes the runner-offline sentence the server sends on the stream.
            setError(err.message || t("sendFailed"));
            resetStream();
            setReloadTick((n) => n + 1);
          },
        })
      );
    },
    [current, busy, withToken, taskId, t, resetStream]
  );

  const handleSend = useCallback(() => {
    const content = inputValue.trim();
    if (!content) return;
    setInputValue("");
    void sendMessage(content);
  }, [inputValue, sendMessage]);

  const handleCancel = useCallback(async () => {
    if (!chat) return;
    try {
      await withToken((token) =>
        api.agentChat.cancelRun(projectId, chat.agentId, chat.conversationId, token)
      );
    } catch {
      // The reply may have just finished — the done event / reload settles the view anyway.
    }
    if (!isStreaming) setReloadTick((n) => n + 1);
  }, [chat, withToken, projectId, isStreaming]);

  const laneLabel = useCallback((key: string) => laneLabelFor(key, tCommon, tDash), [tCommon, tDash]);

  const apply = useCallback(
    async (applyKey: string, request: ApplyTaskChatRequest) => {
      if (applying) return;
      setApplying(applyKey);
      setError(null);
      try {
        const result = await withToken((token) => api.tasks.applyChat(taskId, request, token));
        toast(t(TASK_DISCUSS_APPLIED_KEYS[result.action] ?? "appliedPosted", { lane: laneLabel(result.lane) }));
        onApplied?.(result);
      } catch (err) {
        toast(extractErrorMessage(err, t("applyFailed")), "error");
      } finally {
        setApplying(null);
      }
    },
    [applying, withToken, taskId, toast, t, laneLabel, onApplied]
  );

  const mode = taskDiscussApplyMode(lane || chat?.lane);
  const applyKeys = TASK_DISCUSS_APPLY_KEYS[mode];
  const agentName = chat?.agentName ?? "";
  const hasAssistantReply = messages.some((m) => m.role === "assistant" && !m.id.startsWith("temp-"));
  const lastAssistantIndex = messages.reduce((last, m, i) => (m.role === "assistant" ? i : last), -1);

  return (
    <div className="flex flex-col">
      {/* Agent picker + summary apply */}
      <div className="flex flex-wrap items-center justify-between gap-2 border-b border-white/[0.04] px-3 py-2 lg:px-4">
        <div className="min-w-0 w-48">
          <Select
            size="sm"
            aria-label={t("agentLabel")}
            value={requestedAgentId || loaded?.chat.defaultAgentId || ""}
            disabled={busy || !loaded}
            onChange={(e) => {
              setError(null);
              setRequestedAgentId(e.target.value === loaded?.chat.defaultAgentId ? "" : e.target.value);
            }}
          >
            {(loaded?.chat.agents ?? []).map((agent) => (
              <option key={agent.id} value={agent.id}>
                {agent.name}
              </option>
            ))}
          </Select>
        </div>
        {canExecute && hasAssistantReply && (
          <Button
            size="sm"
            variant="secondary"
            disabled={busy || applying !== null}
            loading={applying === "summary"}
            onClick={() => void apply("summary", { summarize: true, agentId: chat?.agentId })}
          >
            {applying === "summary" ? t("applying") : t(applyKeys.summary)}
          </Button>
        )}
      </div>

      {/* Messages */}
      <div ref={scrollRef} className="max-h-[60vh] min-h-48 space-y-4 overflow-y-auto p-3 lg:p-4">
        {isLoading ? (
          <div className="flex items-center justify-center py-8" aria-label={t("loading")}>
            <TypingDots />
          </div>
        ) : currentLoadError ? (
          <div className="flex flex-col items-center gap-3 py-8 text-center">
            <p className="text-sm text-gray-400">{currentLoadError}</p>
            <Button size="sm" variant="secondary" onClick={() => setReloadTick((n) => n + 1)}>
              {t("retry")}
            </Button>
          </div>
        ) : (
          <>
            {messages.length === 0 && !busy && (
              <div className="flex flex-col items-center py-8 text-center">
                <Avatar name={agentName} size="lg" className="mb-3" />
                <p className="max-w-md text-sm text-gray-400">{t("intro", { agentName })}</p>
              </div>
            )}
            {messages.map((message, idx) => (
              <DiscussBubble
                key={message.id}
                message={message}
                agentName={agentName}
                youLabel={t("you")}
                interactive={canExecute && !busy && idx === lastAssistantIndex}
                onQuestionsSubmit={(text) => void sendMessage(text)}
                applyLabel={
                  canExecute && message.role === "assistant" && !message.id.startsWith("temp-")
                    ? applying === message.id
                      ? t("applying")
                      : t(applyKeys.message)
                    : null
                }
                applyDisabled={busy || applying !== null}
                onApply={() => void apply(message.id, { messageId: message.id, agentId: chat?.agentId })}
              />
            ))}

            {isStreaming && thinkingText && !streamingText && (
              <p className="ml-11 whitespace-pre-wrap text-xs leading-relaxed text-violet-300/80">
                {thinkingText}
              </p>
            )}
            {isStreaming && streamingText && (
              <DiscussBubble
                message={{ id: "streaming", role: "assistant", content: streamingText, createdAt: "" }}
                agentName={agentName}
                youLabel={t("you")}
                streaming
              />
            )}
            {busy && (
              <div className="ml-11 flex items-center gap-2">
                <TypingDots />
                <span className="truncate text-xs text-gray-400">
                  {toolLabel ? t("usingTool", { tool: toolLabel }) : t("working", { agentName })}
                </span>
              </div>
            )}
          </>
        )}
      </div>

      {error && (
        <div
          role="alert"
          className="mx-3 mb-2 rounded-lg border border-red-500/20 bg-red-500/10 px-3 py-2 text-xs text-red-400 lg:mx-4"
        >
          {error}
        </div>
      )}

      {/* Input */}
      <RequirePermission permission="TasksExecute">
        <div className="flex items-end gap-2 border-t border-white/[0.04] p-3">
          <textarea
            value={inputValue}
            onChange={(e) => setInputValue(e.target.value)}
            onKeyDown={(e) => {
              if (e.key === "Enter" && !e.shiftKey) {
                e.preventDefault();
                handleSend();
              }
            }}
            placeholder={t("placeholder", { agentName })}
            aria-label={t("placeholder", { agentName })}
            rows={1}
            disabled={busy || !chat}
            className={cn(
              "block min-h-10 max-h-32 w-full flex-1 resize-none rounded-xl px-4 py-[9px] text-sm leading-5 text-gray-100",
              "border border-white/[0.06] bg-white/[0.03] placeholder:text-gray-400",
              "focus:border-primary-500/50 focus:bg-white/[0.06] focus:outline-none",
              "disabled:opacity-50"
            )}
          />
          {busy ? (
            <Button
              onClick={() => void handleCancel()}
              aria-label={t("stop")}
              title={t("stop")}
              className="h-10 w-10 shrink-0 !rounded-xl !p-0"
            >
              <svg width="16" height="16" viewBox="0 0 24 24" fill="currentColor" aria-hidden="true">
                <rect x="6" y="6" width="12" height="12" rx="2" />
              </svg>
            </Button>
          ) : (
            <Button
              onClick={handleSend}
              disabled={!inputValue.trim() || !chat}
              aria-label={t("send")}
              title={t("send")}
              className="h-10 w-10 shrink-0 !rounded-xl !p-0"
            >
              <svg width="16" height="16" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2" aria-hidden="true">
                <path d="M22 2L11 13M22 2l-7 20-4-9-9-4 20-7z" strokeLinecap="round" strokeLinejoin="round" />
              </svg>
            </Button>
          )}
        </div>
      </RequirePermission>
    </div>
  );
}

function TypingDots() {
  return (
    <span className="flex items-center gap-1" aria-hidden="true">
      <span className="h-1.5 w-1.5 animate-bounce rounded-full bg-gray-400 [animation-delay:0ms]" />
      <span className="h-1.5 w-1.5 animate-bounce rounded-full bg-gray-400 [animation-delay:150ms]" />
      <span className="h-1.5 w-1.5 animate-bounce rounded-full bg-gray-400 [animation-delay:300ms]" />
    </span>
  );
}

function DiscussBubble({
  message,
  agentName,
  youLabel,
  interactive = false,
  onQuestionsSubmit,
  applyLabel = null,
  applyDisabled = false,
  onApply,
  streaming = false,
}: {
  message: TaskChatMessage;
  agentName: string;
  youLabel: string;
  /** Latest assistant reply while idle — its question cards accept answers. */
  interactive?: boolean;
  onQuestionsSubmit?: (text: string) => void;
  /** Lane-adapted "apply to task" label; null hides the action. */
  applyLabel?: string | null;
  applyDisabled?: boolean;
  onApply?: () => void;
  streaming?: boolean;
}) {
  const isUser = message.role === "user";
  const segments = useMemo(
    () => (isUser ? null : splitQuestionSegments(message.content)),
    [isUser, message.content]
  );
  const answers = useMemo(() => (isUser ? parseQuestionAnswers(message.content) : null), [isUser, message.content]);
  const lastQuestionsIndex = segments?.reduce((last, s, i) => (s.type === "questions" ? i : last), -1) ?? -1;

  return (
    <div className={cn("flex max-w-[85%] gap-3", isUser && "ml-auto flex-row-reverse")}>
      <Avatar name={isUser ? youLabel : agentName} size="sm" className="mt-1 shrink-0" />
      <div className={cn("flex min-w-0 flex-col gap-1", isUser ? "items-end" : "items-start")}>
        <div
          className={cn(
            "min-w-0 max-w-full overflow-hidden rounded-2xl px-4 py-2.5 text-sm",
            isUser ? "rounded-tr-md bg-primary-600/20 text-gray-200" : "rounded-tl-md bg-white/[0.04] text-gray-300"
          )}
        >
          {isUser || !segments ? (
            answers ? (
              <QuestionAnswers answers={answers} />
            ) : (
              <p className="whitespace-pre-wrap leading-relaxed">{message.content}</p>
            )
          ) : (
            <QuestionsGroup onSubmit={onQuestionsSubmit}>
              {segments.map((segment, i) =>
                segment.type === "text" ? (
                  <Markdown key={i} className="text-inherit">
                    {segment.content}
                  </Markdown>
                ) : segment.type === "questions" ? (
                  <QuestionsCard
                    key={i}
                    questions={segment.questions}
                    interactive={interactive && !streaming}
                    groupKey={i}
                    ownsSubmit={i === lastQuestionsIndex}
                  />
                ) : (
                  <QuestionsInProgress key={i} />
                )
              )}
            </QuestionsGroup>
          )}
        </div>
        {!streaming && (
          <div className="flex items-center gap-2 px-1">
            {message.createdAt && (
              <span
                className="font-mono text-xs text-gray-400"
                title={new Date(message.createdAt).toLocaleString()}
              >
                {formatMessageTime(message.createdAt)}
              </span>
            )}
            {applyLabel && (
              <button
                type="button"
                onClick={onApply}
                disabled={applyDisabled}
                className="rounded-md px-1.5 py-0.5 text-xs font-medium text-primary-300 transition-colors hover:bg-primary-500/10 hover:text-primary-200 disabled:cursor-not-allowed disabled:opacity-50"
              >
                {applyLabel}
              </button>
            )}
          </div>
        )}
      </div>
    </div>
  );
}

export { TaskDiscussPanel };
