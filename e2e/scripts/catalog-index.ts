/**
 * Validate every catalog/NN-*.md file, write catalog/index.json, catalog/COVERAGE.md and the
 * `CaseId` type used by specs. `--coverage` also scans tests/ for `caseIds(...)` links and marks
 * cases with no linking spec but `automation: automated` as issues.
 * `npm run catalog:index` / `npm run catalog:coverage`
 */
import fs from "node:fs";
import path from "node:path";
import { paths } from "../config/index.js";
import { loadCatalog, type CatalogCase } from "../src/catalog/parse.js";

const wantCoverage = process.argv.includes("--coverage");
const syncAutomation = process.argv.includes("--sync-automation");
let { files, cases, issues } = loadCatalog();

// Spec links: caseIds("HYB-001", "HYB-002")
const linked = new Map<string, Set<string>>();
function scanTests(dir: string) {
  if (!fs.existsSync(dir)) return;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) scanTests(full);
    else if (entry.name.endsWith(".spec.ts")) {
      const rel = path.relative(paths.root, full).replace(/\\/g, "/");
      const text = fs.readFileSync(full, "utf8");
      for (const m of text.matchAll(/caseIds\(([^)]*)\)/g)) {
        for (const id of m[1].matchAll(/["'`]([A-Z][A-Z0-9]{1,5}-\d{3,4})["'`]/g)) {
          if (!linked.has(id[1])) linked.set(id[1], new Set());
          linked.get(id[1])!.add(rel);
        }
      }
    }
  }
}
scanTests(path.join(paths.root, "tests"));
const known = new Set(cases.map((c) => c.id));
for (const c of cases) c.tests = [...(linked.get(c.id) ?? [])].sort();
// --sync-automation: a case a spec links to is `automated`; rewrite `planned` → `automated` in place.
if (syncAutomation) {
  const byFile = new Map<string, CatalogCase[]>();
  for (const c of cases) if (c.tests.length && c.automation === "planned") byFile.set(c.file, [...(byFile.get(c.file) ?? []), c]);
  for (const [rel, list] of byFile) {
    const abs = path.join(paths.root, rel);
    const lines = fs.readFileSync(abs, "utf8").split(/\r?\n/);
    for (const c of list) {
      for (let i = c.line; i < Math.min(lines.length, c.line + 40); i++) {
        if (/^automation:\s*planned\s*$/.test(lines[i])) {
          lines[i] = "automation: automated";
          break;
        }
        if (/^## /.test(lines[i])) break;
      }
    }
    fs.writeFileSync(abs, lines.join("\n"));
    console.log(`marked ${list.length} case(s) automated in ${rel}`);
  }
  ({ files, cases, issues } = loadCatalog());
  for (const c of cases) c.tests = [...(linked.get(c.id) ?? [])].sort();
}
for (const [id, specs] of linked) if (!known.has(id)) issues.push({ file: [...specs][0], line: 0, message: `spec links unknown case id ${id}` });
if (wantCoverage) {
  for (const c of cases) {
    if (c.automation === "automated" && c.tests.length === 0) issues.push({ file: c.file, line: c.line, message: `${c.id}: automation=automated but no spec links it` });
  }
}

const count = <K extends string>(items: CatalogCase[], key: (c: CatalogCase) => K | K[]) => {
  const out: Record<string, number> = {};
  for (const c of items) for (const k of [key(c)].flat()) out[k] = (out[k] ?? 0) + 1;
  return out;
};

const refIndex = {
  apiRoutes: [...new Set(cases.flatMap((c) => c.refs.filter((r) => /^orkka-api:(GET|POST|PUT|PATCH|DELETE) /.test(r)).map((r) => r.slice("orkka-api:".length))))].sort(),
  uiPages: [...new Set(cases.flatMap((c) => c.refs.filter((r) => /^orkka-ui:(local:)?\//.test(r)).map((r) => r.slice("orkka-ui:".length))))].sort(),
  adminPages: [...new Set(cases.flatMap((c) => c.refs.filter((r) => r.startsWith("admin-ui:")).map((r) => r.slice("admin-ui:".length))))].sort(),
  i18nNamespaces: [...new Set(cases.flatMap((c) => c.refs.filter((r) => r.startsWith("i18n:")).map((r) => r.slice("i18n:".length))))].sort(),
  hubEvents: [...new Set(cases.flatMap((c) => c.refs.filter((r) => r.startsWith("hub:")).map((r) => r.slice("hub:".length))))].sort(),
  cliVerbs: [...new Set(cases.flatMap((c) => c.refs.filter((r) => r.startsWith("cli:")).map((r) => r.slice("cli:".length))))].sort(),
};

const index = {
  generatedAt: new Date().toISOString(),
  counts: {
    total: cases.length,
    files: files.length,
    byArea: count(cases, (c) => c.area),
    byAutomation: count(cases, (c) => c.automation),
    byPriority: count(cases, (c) => c.priority),
    byMode: count(cases, (c) => c.modes),
    linkedToSpecs: cases.filter((c) => c.tests.length > 0).length,
  },
  refs: refIndex,
  cases,
};
fs.writeFileSync(path.join(paths.catalog, "index.json"), JSON.stringify(index, null, 2) + "\n");

// CaseId type for specs.
const typeFile = path.join(paths.root, "src", "fixtures", "case-ids.d.ts");
fs.writeFileSync(typeFile, `// GENERATED by scripts/catalog-index.ts — do not edit.\nexport type KnownCaseId =\n${cases.map((c) => `  | "${c.id}"`).join("\n")};\n`);

// COVERAGE.md
const areas = [...new Set(cases.map((c) => c.area))].sort();
const rows = areas.map((a) => {
  const cs = cases.filter((c) => c.area === a);
  const f = files.find((x) => x.area === a);
  const n = (k: string) => cs.filter((c) => c.automation === k).length;
  const linkedN = cs.filter((c) => c.tests.length > 0).length;
  const p0 = cs.filter((c) => c.priority === "P0").length;
  const p0Linked = cs.filter((c) => c.priority === "P0" && c.tests.length > 0).length;
  return `| ${a} | ${f?.title ?? ""} | ${cs.length} | ${p0} | ${linkedN} | ${p0Linked} | ${n("automated")} | ${n("planned")} | ${n("manual")} | ${n("blocked")} |`;
});
const coverage = [
  "# Catalogue coverage",
  "",
  `Generated ${index.generatedAt}. ${cases.length} cases in ${files.length} files; ${index.counts.linkedToSpecs} linked to a spec.`,
  "",
  "| Area | Title | Cases | P0 | Linked | P0 linked | automated | planned | manual | blocked |",
  "|---|---|---:|---:|---:|---:|---:|---:|---:|---:|",
  ...rows,
  "",
  "## By mode",
  "",
  "| Mode | Cases |",
  "|---|---:|",
  ...Object.entries(index.counts.byMode)
    .sort()
    .map(([m, n]) => `| ${m} | ${n} |`),
  "",
].join("\n");
fs.writeFileSync(path.join(paths.catalog, "COVERAGE.md"), coverage);

console.log(`catalog: ${cases.length} cases in ${files.length} files; linked to specs: ${index.counts.linkedToSpecs}`);
console.log(`by automation: ${JSON.stringify(index.counts.byAutomation)}`);
console.log(`by priority:   ${JSON.stringify(index.counts.byPriority)}`);
if (issues.length) {
  console.error(`\n${issues.length} issue(s):`);
  for (const i of issues.slice(0, 200)) console.error(`  ${i.file}:${i.line} ${i.message}`);
  if (issues.length > 200) console.error(`  … ${issues.length - 200} more`);
  process.exit(1);
}
